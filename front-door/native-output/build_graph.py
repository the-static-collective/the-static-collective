#!/usr/bin/env python3
"""NATIVE-OUTPUT-010: inspect real CANNON artifacts, then use original Free Graph.
Not an authority engine, publication decision, member match or automated dispatch.
"""
import argparse, hashlib, html, json, os, sys
from pathlib import Path

FILES = (
    ("cannon", "culture-out/receipt.json", "CANNON source-verified cultural artifact", "artifact"),
    ("press", "press-held/hold-receipt.json", "lemonPRESS independent editorial HOLD", "receipt"),
    ("relatte", "sovereign-hold/roundtrip.json", "GHoT and reLATTE signed receiver-local HOLD", "receipt"),
    ("planz", "return-loop/planz-hold.json", "planZ open planning gate", "receipt"),
    ("graft", "return-loop/graft-nursery.json", "GRAFT nursery candidate, no branch created", "receipt"),
    ("jarvis", "return-loop/jarvis-attention.json", "JAR;VIS bounded attention candidate", "receipt"),
)
# The original Free Graph source is checked out separately, at an immutable source revision.
def run(base: Path, freegraph: Path, out: Path, scenario: str):
    if out.exists():
        raise ValueError("OUTPUT_EXISTS: never overwrite a previous receipt or graph")
    root = freegraph.resolve()
    if not (root / "scripts" / "fg_core.py").is_file():
        raise ValueError("NATIVE_FREE_GRAPH_MISSING")
    sys.path.insert(0, str(root))
    from scripts.fg_ops import rehash_packet
    from scripts.fg_core import validate_packet, packet_id
    readings = []
    for key, rel, title, kind in FILES:
        path = base / rel
        raw = path.read_bytes()
        if not raw or len(raw) > 1000000:
            raise ValueError("INVALID_NATIVE_ARTIFACT_" + key)
        value = json.loads(raw)
        if not isinstance(value, dict) or not value.get("schema"):
            # Some source-owned receipts may use a different head field. Do not fabricate.
            if key != "press" or not isinstance(value, dict):
                raise ValueError("WRONG_NATIVE_RECEIPT_SHAPE_" + key)
        readings.append((key, rel, title, kind, raw, value))
    # Refuse to invent real-world benefits from the synthetic original donor chain.
    ret = readings[-1][-1]
    graft = readings[-2][-1]
    planz = readings[-3][-1]
    if ret.get("localTaskCreated") is True or ret.get("externalMessageSent") is True:
        raise ValueError("JARVIS_EFFECT_ESCALATED")
    if graft.get("branchCreated") is not False or planz.get("planUpdated") is not False:
        raise ValueError("GRAFT_OR_PLANZ_EFFECT_ESCALATED")
    seed = "sha256:" + "0" * 64
    sources = []
    nodes = []
    links = []
    for key, rel, title, kind, raw, _value in readings:
        digest = "sha256:" + hashlib.sha256(raw).hexdigest()
        sid = "fgs:" + key
        nid = "fgn:" + key
        sources.append({
            "id": sid, "source_class": "specimen-receipt",
            "authority": "source-local",
            "locator": {"system": "CANNON 005 original native CI", "coordinate": rel,
                        "revision": "immutable checked-out CANNON native source",
                        "resolution": "original generated bytes in uploaded artifact"},
            "digest": digest, "access": "public", "export": "portable",
            "excerpt": title + "; exactly SHA-256 " + digest + "; synthetic/no field effects."
        })
        nodes.append({"id": nid, "kind": kind, "label": title,
                      "source_ids": [sid], "status": "observed",
                      "aliases": ["fg://cannon-native/" + key]})
    # Exactly the source-reported computational edges. No constitutes, owner-local or adoption.
    for (a, b, label) in (
        ("cannon", "press", "submitted-for-independent-HOLD"),
        ("press", "relatte", "reviewed-and-transported-as-HOLD"),
        ("relatte", "planz", "triaged-for-unapplied-owner-review"),
        ("planz", "graft", "candidate-nursery-not-created-branch"),
        ("graft", "jarvis", "source-owned-attention-held")
    ):
        links.append({"id": "fgl:" + a + "-" + b,
                      "from": "fgn:" + a, "to": "fgn:" + b,
                      "verb": "connects", "qualifier": label,
                      "status": "observed", "authority": "none",
                      "source_ids": ["fgs:" + a, "fgs:" + b]})
    packet = {
        "schema": "free-graph.packet/v0",
        "purpose": "Preserve native machine-output lineage from source-owned CANNON→lemonPRESS→reLATTE→planZ→GRAFT→JAR;VIS; no real-world admission.",
        "modes": ["re-enter"],
        "scope": {"task": "Source-verified synthetic cultural artifact lineage",
                  "worlds": ["CANNON", "lemonPRESS", "GHoT/reLATTE", "planZ", "GRAFT", "JAR;VIS", "Free Graph"],
                  "resolution": "Six witnessed machine outputs only"},
        "task_world_cut": {
            "status": "sufficient", "selected_ids": [s["id"] for s in sources] +
              [n["id"] for n in nodes] + [l["id"] for l in links],
            "owner_head_source_ids": [],
            "omitted": [{"door": "Real rights and human beneficiary", "reason": "No verified recipient or field consent."}],
            "rationale": "This graph asserts only inspected native software-file provenance."
        },
        "sources": sources, "nodes": nodes, "links": links,
        "non_imports": ["Native software output is not verified human work.",
                        "Signed synthetic transport is not a real person's consent.",
                        "GRAFT candidate is not a created Git branch or approved publication."],
        "residual_fog": ["No field-tested human outcome.",
                         "No granted publishing rights or independent beneficiary.",
                         "CANNON selected scenario does not alter its fixed planZ ATLAS-BRIDGE-002 triage."],
        "extensions": {"scenario": scenario, "origin": "native-cannon-005-ci", "authorityEffect": "none"}
    }
    original = rehash_packet(packet, stamp=True)
    errors = validate_packet(original)
    if errors:
        raise ValueError("NATIVE_FREE_GRAPH_REFUSED: " + "; ".join(errors))
    out.mkdir(parents=True)
    graph_file = out / "free-graph.packet.json"
    graph_file.write_text(json.dumps(original, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    # Reusable inspectable representation of the exact graph: labels are HTML-escaped,
    # links are never machine-level permissions and SVG has no remote resources.
    x_positions = (34, 272, 510, 748, 986, 1224)
    y = 65
    chunks = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1485 240" role="img" aria-labelledby="title desc">',
        '<title id="title">Native CANNON culture-return software lineage</title>',
        '<desc id="desc">Six source-verified machine artifacts. All remain held, synthetic or non-admitted; no human effect.</desc>',
        '<rect width="1485" height="240" fill="#f3f5ed"/>'
    ]
    for i, n in enumerate(original["nodes"]):
        x = x_positions[i]
        label = html.escape(n["label"])
        chunks.append(f'<rect x="{x}" y="{y}" width="215" height="106" rx="8" fill="#fffefa" stroke="#315c41" stroke-width="2"/>')
        chunks.append(f'<text x="{x+11}" y="{y+25}" font-family="system-ui" font-weight="700" font-size="15" fill="#23432f">{html.escape(FILES[i][0]).upper()}</text>')
        # limit long natural-language descriptions in the diagram only (not original packet)
        words = label.split()
        row, rows = "", []
        for w in words:
            if len(row + " " + w) > 28 and row:
                rows.append(row)
                row = ""
            row = (row + " " + w).strip()
        if row:
            rows.append(row)
        for j, row in enumerate(rows[:3]):
            chunks.append(f'<text x="{x+11}" y="{y+52+17*j}" font-family="system-ui" font-size="12" fill="#344e3c">{row}</text>')
        if i:
            chunks.append(f'<path d="M {x-22} {y+53} L {x-8} {y+53}" stroke="#417052" stroke-width="3"/>')
            chunks.append(f'<path d="M {x-11} {y+48} L {x-5} {y+53} L {x-11} {y+58}" fill="none" stroke="#417052" stroke-width="2"/>')
    chunks.append('<text x="34" y="210" font-family="system-ui" font-size="14" fill="#405b49">ORIGINAL NATIVE OUTPUTS VERIFIED · HUMAN PARTICIPATION / PUBLICATION / ADOPTION NOT VERIFIED</text></svg>')
    (out / "source-graph.svg").write_text("\n".join(chunks) + "\n", encoding="utf-8")
    (out / "graph-receipt.json").write_text(json.dumps({
        "schema": "abundent/native-output-graph-receipt-v1",
        "freeGraphNativeValidated": True, "packetId": packet_id(original),
        "nodes": len(nodes), "links": len(links),
        "sourceOutputDigests": {key: "sha256:" + hashlib.sha256(raw).hexdigest()
                               for key, _rel, _title, _kind, raw, _value in readings},
        "status": "SOURCE_NATIVE_SYNTHETIC_NO_FIELD_ADOPTION",
        "humanOutcomeVerified": False, "publicationAuthorized": False
    }, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"packet_id": packet_id(original), "graph": str(graph_file), "nativeOriginal": True,
                      "fieldVerified": False}))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--base", default=".")
    p.add_argument("--freegraph", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--scenario", choices=("garden", "application", "creative"), default="garden")
    a = p.parse_args()
    run(Path(a.base), Path(a.freegraph), Path(a.out), a.scenario)
